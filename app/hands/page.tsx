/**
 * JSON-LD는 **서버에서** 내보낸다.
 *
 * ★2026-08-13: 원래 hands-client.tsx가 Article·BreadcrumbList를 만들어
 *   `<SEO schema={jsonLd}>`로 넘기고 있었는데 `components/seo.tsx`는 `schema`를
 *   구조분해에서 받지도 않는다 — **한 번도 출력된 적이 없는 죽은 코드였다.**
 *   라이브 실측에서도 ld+json이 루트 layout의 WebSite 1개뿐이었다.
 *
 * 타입은 ItemList로 잡았다. 이 페이지의 본체가 «순위가 매겨진 10단계 표»라
 * Article보다 정확하고, 순위형 리치결과·AI 발췌에 그대로 쓰인다.
 * (Article은 저자·발행일이 있어야 맞는 타입이라 도구 페이지에는 부적합했다.)
 */
export default function Page() {
  const jsonLd = [
    {
      "@context": "https://schema.org",
      "@type": "ItemList",
      /**
       * 🔴 name이 필라 itemList와 괄호 안까지 동일했다(「(텍사스 홀덤 7장 기준, 강→약 10단계)」).
       *   10개 아이템의 이름·설명·확률까지 같은 검산본이라, 구조화 데이터 레벨에서 두 페이지가
       *   사실상 같은 문서로 보였다. 확률이 같은 건 옳다(§13) — 갈라야 할 건 name·description이다.
       *   그 문구는 필라에 양보하고 여기는 «예시 카드·한 화면»이라는 도구 고유값을 적는다.
       */
      name: "포커 족보 10단계 표 — 예시 카드와 7장 기준 확률",
      description:
        "각 족보가 실제 카드 다섯 장으로 어떻게 생겼는지 한 화면에서 확인하는 표입니다.",
      itemListOrder: "https://schema.org/ItemListOrderDescending",
      numberOfItems: HANDS.length,
      itemListElement: HANDS.map((h) => ({
        "@type": "ListItem",
        position: h.rank,
        name: h.name.split(" (")[0],
        description: `${h.example.join(" ")} · ${h.description} 홀덤 7장 기준 ${h.prob}`,
      })),
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "홈", item: `${SITE}/` },
        // ⚠ H1에서 「포커 족보 순위」 축어를 비운 근거가 여기에도 적용된다 —
        //   빵부스러기는 SERP에 노출되므로 같은 기준으로 맞춘다(교열 렌즈 적발).
        //   푸터 링크 라벨만 「족보 순위표」로 두는데, 그쪽은 사용자가 메뉴에서 찾는 이름이라 명료성이 우선이다.
        { "@type": "ListItem", position: 2, name: "포커 족보 10단계 표", item: `${SITE}/hands` },
      ],
    },
    /**
     * FAQPage — 화면의 FAQ와 **같은 배열**에서 만든다.
     * ⚠ 구글 FAQ 리치결과는 2026-05-07에 종료됐지만 마크업 자체는 유효하다
     *   (Bing·Perplexity·RAG가 파싱한다). 본문에도 같은 문장이 있어야 LLM이 읽는다 —
     *   스키마에만 있는 정보는 못 읽는다(posting.mdc §GEO).
     */
    {
      "@context": "https://schema.org",
      "@type": "FAQPage",
      mainEntity: FAQS.map(({ q, a }) => ({
        "@type": "Question",
        name: q,
        acceptedAnswer: { "@type": "Answer", text: a },
      })),
    },
  ];

  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <HandsClient />
    </>
  );
}

const MAP: Partial<Record<SecondaryLocale, AuthText>> = {
  en: EN, ja: JA, es: ES, pt: PT, de: DE, zh: ZH, "zh-hant": ZH_HANT, fr: FR,
  id: ID, ms: MS, hi: HI, vi: VI, tr: TR, ar: AR, ru: RU,
};

/** `next` 경로(쿼리·해시 포함 가능)에서 화면 언어를 고른다. 루트 경로 = 한국어. */
export function authLocaleFromNext(next: string): SecondaryLocale | null {
  return localeFromPath(next.split(/[?#]/)[0]);
}

export function authText(locale: SecondaryLocale | null): AuthText {
  if (!locale) return KO;
  return MAP[locale] ?? EN;
}

/** <html lang/dir> 값 — 사전이 없는 로케일은 EN 문구가 나가므로 lang도 en. */
export function authHtmlAttrs(locale: SecondaryLocale | null): { lang: string; dir: "rtl" | "ltr" } {
  if (!locale) return { lang: "ko", dir: "ltr" };
  if (!MAP[locale]) return { lang: "en", dir: "ltr" };
  return { lang: locale === "zh-hant" ? "zh-Hant" : locale === "zh" ? "zh-Hans" : locale, dir: RTL_LOCALES.includes(locale) ? "rtl" : "ltr" };
}

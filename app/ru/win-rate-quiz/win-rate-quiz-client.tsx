/** 러시아어 수사 뒤 명사 형태: 1 · 2–4 · 5+ (11–14는 5+). */
const pl = (k: number, one: string, few: string, many: string) => {
  const a = Math.abs(k) % 100;
  const b = a % 10;
  if (a >= 11 && a <= 14) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
};

この違いが効くのは、トリップスがセットよりずっとありふれていて、**相手も同じくらい簡単に持てる**からです。セットは珍しく、たいてい最強ハンドです。ペアボードのトリップスは共有地であり、だからこそソルバーはそれをベットの許可証として扱いません。

